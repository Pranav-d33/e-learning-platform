// Extracts Devanagari letter outlines from Baloo 2 (SIL OFL) into SVG path data so the
// tracing guide is a real SVG path, aligned exactly with the coverage skeleton.
// Run: npm run assets:glyphs
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import opentype from "opentype.js";

const FONT_URL = "https://fonts.gstatic.com/s/baloo2/v23/wXK0E3kTposypRydzVT08TS3JnAmtdjEyqpv.ttf";
const FONT_NAME = "Baloo 2 SemiBold";
const CACHE = path.join(process.cwd(), "scripts", ".cache", "Baloo2-SemiBold.ttf");
const OUT = path.join(process.cwd(), "src", "lib", "early", "glyphs-hi.ts");
const CHARS = ["अ", "आ", "इ", "ई", "उ", "ऊ", "ए", "ऐ", "ओ", "औ", "क", "ख", "ग", "घ", "च", "छ", "ज", "ट"];
const GRID = 200;
const MAX_H = 184;
const MAX_W = 184;

if (!existsSync(CACHE)) {
  await mkdir(path.dirname(CACHE), { recursive: true });
  const res = await fetch(FONT_URL);
  if (!res.ok) throw new Error(`Font download failed: HTTP ${res.status}`);
  await writeFile(CACHE, Buffer.from(await res.arrayBuffer()));
}
const buf = await readFile(CACHE);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Measure every glyph at a reference size with the baseline at y=0.
const REF = 1000;
const measured = CHARS.map((ch) => {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`Font has no glyph for ${ch}`);
  const p = glyph.getPath(0, 0, REF);
  return { ch, path: p, box: p.getBoundingBox() };
});

// One shared scale + baseline keeps the headline (शिरोरेखा) at the same height on every letter.
const top = Math.min(...measured.map((m) => m.box.y1));
const bottom = Math.max(...measured.map((m) => m.box.y2));
const widest = Math.max(...measured.map((m) => m.box.x2 - m.box.x1));
const scale = Math.min(MAX_H / (bottom - top), MAX_W / widest);
const baseline = (GRID - (bottom - top) * scale) / 2 - top * scale;

const outlines = {};
for (const { ch, box } of measured) {
  const size = REF * scale;
  const width = (box.x2 - box.x1) * scale;
  const x = (GRID - width) / 2 - box.x1 * scale;
  outlines[ch] = font.charToGlyph(ch).getPath(x, baseline, size).toPathData(1);
}

const body = Object.entries(outlines)
  .map(([ch, d]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(d)},`)
  .join("\n");
await writeFile(
  OUT,
  `// Generated by scripts/build-hindi-glyphs.mjs — do not edit by hand.\n` +
    `// Outlines from ${FONT_NAME} (SIL Open Font License), normalised to a ${GRID}×${GRID} grid.\n` +
    `export const HI_GLYPH_FONT = ${JSON.stringify(FONT_NAME)};\n` +
    `export const HI_OUTLINES: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`Wrote ${CHARS.length} outlines (scale ${scale.toFixed(3)}, baseline y=${baseline.toFixed(1)})`);
